const galleryJs = `<script id="dhb-gallery-js">
(function () {
  var tabs = [].slice.call(document.querySelectorAll('[data-gtab]'));
  var panes = [].slice.call(document.querySelectorAll('[data-gpane]'));
  if (!tabs.length) return;
  tabs.forEach(function (t) {
    t.addEventListener('click', function () {
      var key = t.getAttribute('data-gtab');
      tabs.forEach(function (x) { x.classList.toggle('is-active', x === t); });
      panes.forEach(function (p) { p.classList.toggle('is-active', p.getAttribute('data-gpane') === key); });
    });
  });
})();
</script>`

