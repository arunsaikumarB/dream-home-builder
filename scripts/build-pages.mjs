// Builds the inner pages from a single shared shell extracted out of index.html.
// index.html itself is READ ONLY here - it is never written.
import fs from 'node:fs'
import path from 'node:path'
import { contactTabsHTML, CONTACT_TABS_JS } from './contact-tabs-partial.mjs'
import { QUOTE_MODAL_HTML } from './quote-modal-partial.mjs'

const ROOT = process.cwd()
const PUB = path.join(ROOT, 'public')
const index = fs.readFileSync(path.join(PUB, 'index.html'), 'utf8')

// ---------- extract shared pieces ----------
const styles = [...index.matchAll(/<style(?: id="[^"]*")?>([\s\S]*?)<\/style>/g)].map((m) => m[1])
if (styles.length < 20) throw new Error('expected the inline style blocks, found ' + styles.length)
fs.mkdirSync(path.join(PUB, 'css'), { recursive: true })
fs.writeFileSync(
  path.join(PUB, 'css', 'dhb-pages.css'),
  '/* GENERATED by scripts/build-pages.mjs from index.html - do not edit by hand */\n' + styles.join('\n\n'),
)

const grab = (re, label) => {
  const m = index.match(re)
  if (!m) throw new Error('missing: ' + label)
  return m[0]
}
let topnav = grab(/<nav class="dhb-topnav"[\s\S]*?<\/nav>/, 'topnav')
let footer = grab(/<footer class="dhb-site-footer"[\s\S]*?<\/footer>/, 'footer')
const namedScript = (id) => grab(new RegExp('<script id="' + id + '">[\\s\\S]*?<\\/script>'), id)
const autohide = namedScript('dhb-header-autohide-js')

// ---------- rewrite in-page anchors to real page urls ----------
const MAP = {
  '#hero': '/',
  '#about': '/about',
  '#services': '/services',
  '#inspired': '/projects',
  '#testimonials': '/testimonials',
  '#quote': '/contact',
}
const toPages = (s) => s.replace(/href="(#[a-z-]+)"/g, (m, a) => (MAP[a] ? 'href="' + MAP[a] + '"' : m))
topnav = toPages(topnav)
footer = toPages(footer)
if (!topnav.includes('href="/about"')) {
  topnav = topnav.replace('<a href="/services">Services</a>', '<a href="/about">About</a>\n  <a href="/services">Services</a>')
}

// pull a section out of index and strip reveal hooks (inner pages don't load Webflow GSAP)
const section = (id) => {
  const at = index.indexOf('id="' + id + '"')
  if (at < 0) throw new Error('section not found: ' + id)
  const s = index.lastIndexOf('<section', at)
  const e = index.indexOf('</section>', at) + '</section>'.length
  return toPages(index.slice(s, e)).replace(/\s+data-scroll-reveal="[^"]*"/g, '')
}

// ---------- content parsed out of index.html ----------
const sliceSection = (id) =>
  index.slice(index.indexOf('id="' + id + '"'), index.indexOf('</section>', index.indexOf('id="' + id + '"')))

const services = [...sliceSection('services').matchAll(
  /<figure><img src="([^"]+)" alt="([^"]*)"[^>]*><\/figure>\s*<h3[^>]*>([^<]+)<\/h3>\s*<p[^>]*>([\s\S]*?)<\/p>/g,
)].map((m) => ({ img: m[1], alt: m[2], title: m[3].trim(), copy: m[4].trim() }))
if (services.length < 4) throw new Error('parsed only ' + services.length + ' services')

const reviews = [...sliceSection('testimonials').matchAll(
  /<blockquote class="dhb-t-quote">([\s\S]*?)<\/blockquote>[\s\S]*?<span class="dhb-t-name">([^<]*)<\/span>\s*<span class="dhb-t-project">([^<]*)<\/span>/g,
)].map((m) => ({ quote: m[1].trim(), name: m[2].trim(), project: m[3].trim() }))
if (reviews.length < 5) throw new Error('parsed only ' + reviews.length + ' reviews')

const pad2 = (n) => (n < 10 ? '0' + n : String(n))
const STARS = '<span class="dhb-stars" role="img" aria-label="Rated 5 out of 5">★★★★★</span>'

// ---------- gallery built from the images actually on disk ----------
const CATS = [
  ['elevation', 'Elevations'],
  ['kitchen', 'Kitchens'],
  ['bathroom', 'Bathrooms'],
  ['interior', 'Interiors'],
  ['bedroom', 'Bedrooms'],
  ['living', 'Living Rooms'],
  ['wetbar', 'Wet Bars'],
  ['patio', 'Patios'],
]
const gallery = CATS.map(([slug, label]) => {
  const dir = path.join(PUB, 'images', 'projects', slug)
  if (!fs.existsSync(dir)) return null
  const files = fs.readdirSync(dir).filter((f) => /\.(jpe?g|png|webp|avif)$/i.test(f)).sort()
  return files.length ? { slug, label, files } : null
}).filter(Boolean)
const totalImgs = gallery.reduce((a, g) => a + g.files.length, 0)

// ---------- mobile nav ----------
// The homepage's hamburger menu is a heavy Webflow/GSAP overlay that depends on
// scripts never loaded on the generated pages (barba, SplitText, lenis, ...).
// Below 992px .dhb-topnav-links and the CTA hide entirely with nothing to
// replace them, so inner pages had NO way to navigate on mobile at all. This
// is a small self-contained substitute, built from the same links already
// extracted into `topnav` so the two can't drift out of sync.
const navLinksBlock = topnav.match(/<div class="dhb-topnav-links">[\s\S]*?<\/div>/)[0]
const mobileLinks = [...navLinksBlock.matchAll(/<a href="([^"]+)">([^<]+)<\/a>/g)]
if (mobileLinks.length < 5) throw new Error('expected at least 5 nav links, parsed ' + mobileLinks.length)

const mobileNav = `<div class="dhb-mnav">
  <button type="button" class="dhb-mnav-btn" data-mnav-open aria-label="Open menu" aria-expanded="false" aria-controls="dhb-mnav-panel">
    <span></span><span></span><span></span>
  </button>
  <div class="dhb-mnav-overlay" data-mnav-close></div>
  <nav class="dhb-mnav-panel" id="dhb-mnav-panel" aria-label="Mobile">
    <button type="button" class="dhb-mnav-close" data-mnav-close aria-label="Close menu">&times;</button>
    <ul>
${mobileLinks.map(([, href, label]) => `      <li><a href="${href}">${label}</a></li>`).join('\n')}
    </ul>
    <a class="dhb-mnav-cta" href="/contact" data-open-quote>Request Quote</a>
  </nav>
</div>`

const mobileNavJs = `<script id="dhb-mobile-nav-js">
(function () {
  var root = document.querySelector('.dhb-mnav');
  if (!root) return;
  var btn = root.querySelector('[data-mnav-open]');
  var panel = root.querySelector('.dhb-mnav-panel');
  function open() {
    root.classList.add('is-open');
    btn.setAttribute('aria-expanded', 'true');
    document.body.classList.add('dhb-modal-open');
  }
  function close() {
    root.classList.remove('is-open');
    btn.setAttribute('aria-expanded', 'false');
    document.body.classList.remove('dhb-modal-open');
  }
  btn.addEventListener('click', open);
  root.querySelectorAll('[data-mnav-close]').forEach(function (el) { el.addEventListener('click', close); });
  panel.querySelectorAll('a:not([data-open-quote])').forEach(function (a) { a.addEventListener('click', close); });
  document.addEventListener('keydown', function (e) { if (e.key === 'Escape') close(); });
})();
</script>`

